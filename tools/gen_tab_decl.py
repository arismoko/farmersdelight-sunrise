#!/usr/bin/env python3
"""Write tools/decl/tabs.toml.in: FD's creative tab (ModCreativeTabs.TAB_FARMERS_DELIGHT).

The tab lists ModItems.CREATIVE_TAB_ITEMS, a LinkedHashSet filled by every register*WithTab call in
source order, so the order is the order of those calls in ModItems.java. Items this port has not
declared yet are listed too: Horizon leaves out items the game doesn't have, and they appear as their
milestones declare them. Run tools/gen_decls.py afterwards.

Usage: gen_tab_decl.py --fd <FarmersDelightRefabricated checkout>
"""
import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
J = "src/main/java/vectorwing/farmersdelight/common"


def constants(path: Path) -> dict[str, str]:
    return dict(re.findall(r'(\w+)\s*=\s*(?:id|key)\(\s*"([a-z0-9_]+)"', path.read_text()))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--fd", required=True, type=Path)
    fd = ap.parse_args().fd
    ids = {
        "ModItemIds": constants(fd / J / "references/ModItemIds.java"),
        "ModBlockItemIds": constants(fd / J / "references/ModBlockItemIds.java"),
    }
    source = (fd / J / "registry/ModItems.java").read_text()
    # `DYED_X.lightGray()` is a ColorCollection entry: createSimpleColored("x") names it `light_gray_x`.
    colored = dict(
        re.findall(
            r'(\w+)\s*=\s*createSimpleColored\(\s*"([a-z0-9_]+)"',
            (fd / J / "references/ModBlockItemIds.java").read_text(),
        )
    )
    calls = re.findall(
        r"register\w*WithTab\(\s*(ModItemIds|ModBlockItemIds)\.(\w+)(?:\.([a-zA-Z]+)\(\)\.item\(\))?", source
    )
    declared = len(re.findall(r"\bregister\w*WithTab\(", source)) - len(
        re.findall(r"Supplier<Item> register\w*WithTab\(", source)
    )
    if len(calls) != declared:
        print(f"{declared} register*WithTab calls but {len(calls)} resolved", file=sys.stderr)
        return 1
    items = []
    for cls, name, colour in calls:
        if name in colored and colour:
            snake = re.sub(r"([A-Z])", lambda m: "_" + m.group(1).lower(), colour)
            items.append(f"farmersdelight:{snake}_{colored[name]}")
        else:
            items.append(f"farmersdelight:{ids[cls][name]}")
    if len(set(items)) != len(items):
        print("duplicate tab items", file=sys.stderr)
        return 1
    lines = [
        "# GENERATED by tools/gen_tab_decl.py from J/common/registry/ModItems.java (register*WithTab order) and",
        "# J/common/registry/ModCreativeTabs.java (title itemGroup.farmersdelight, icon the stove). Do not edit.",
        "",
        "[farmersdelight]",
        'source = "J/common/registry/ModCreativeTabs.java:TAB_FARMERS_DELIGHT; J/common/registry/ModItems.java:CREATIVE_TAB_ITEMS"',
        'title = "itemGroup.farmersdelight"',
        'icon = "farmersdelight:stove"',
        "items = [",
        *[f'  "{item}",' for item in items],
        "]",
        "",
    ]
    (REPO / "tools/decl/tabs.toml.in").write_text("\n".join(lines))
    print(f"wrote tools/decl/tabs.toml.in: {len(items)} items")
    return 0


if __name__ == "__main__":
    sys.exit(main())
