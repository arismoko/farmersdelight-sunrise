#!/usr/bin/env python3
"""Generate src/items/food_tooltips.rs: the effect lines FD's food tooltips show (M9-04).

ConsumableItem#appendHoverText shows `TextUtils.addFoodEffectTooltip` for items built with
`hasFoodEffectTooltip` and a blue `tooltip.farmersdelight.<path>` line for `hasCustomTooltip`
(J/common/registry/ModItems.java). The effects are each item's `minecraft:apply_effects` consume
effects, read from its declaration in tools/decl/items.toml.in, so the table follows the declarations.
`--check` verifies the generated file is current.
"""
import argparse
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DECL = ROOT / "tools/decl/items.toml.in"
OUT = ROOT / "src/items/food_tooltips.rs"

# ModItems.java: ConsumableItem(properties, hasFoodEffectTooltip, hasCustomTooltip).
CUSTOM = ["milk_bottle", "hot_cocoa", "melon_juice"]
EFFECTS = [
    "apple_cider", "tomato_sauce", "melon_popsicle", "glow_berry_custard", "fruit_salad", "mixed_salad",
    "nether_salad", "barbecue_stick", "egg_sandwich", "chicken_sandwich", "hamburger", "bacon_sandwich",
    "mutton_wrap", "dumplings", "stuffed_potato", "cabbage_rolls", "salmon_roll", "cod_roll", "kelp_roll",
    "kelp_roll_slice", "cooked_rice", "bone_broth", "beef_stew", "chicken_soup", "vegetable_soup", "fish_stew",
    "fried_rice", "pumpkin_soup", "baked_cod_stew", "noodle_soup", "onion_soup", "bacon_and_eggs",
    "pasta_with_meatballs", "pasta_with_mutton_chop", "mushroom_rice", "roasted_mutton_chops",
    "vegetable_noodles", "steak_and_potatoes", "ratatouille", "squid_ink_pasta", "grilled_salmon",
    "roast_chicken", "stuffed_pumpkin", "honey_glazed_ham", "shepherds_pie", "gleaming_salad",
]


def effects(decl: dict, path: str) -> list[tuple[str, int, int]]:
    consumable = decl[path].get("components", {}).get("minecraft:consumable", {})
    out = []
    for entry in consumable.get("on_consume_effects", []):
        if entry.get("type") == "minecraft:apply_effects":
            for e in entry["effects"]:
                out.append((e["id"], int(e.get("duration", 0)), int(e.get("amplifier", 0))))
    return out


def render() -> str:
    decl = tomllib.loads(DECL.read_text())
    lines = [
        "// @generated by tools/gen_food_tooltips.py from tools/decl/items.toml.in; do not edit.",
        "//! The items whose tooltip lists their consume effects, and those with FD's blue custom line.",
        "",
        "/// One consume effect: (effect, duration, amplifier).",
        "pub type Effect = (&'static str, i32, i32);",
        "",
        "/// (item, effects) for `hasFoodEffectTooltip` items.",
        "pub const EFFECT_TOOLTIPS: &[(&str, &[Effect])] = &[",
    ]
    for path in EFFECTS:
        if path not in decl:
            sys.exit(f"{path}: no declaration")
        body = ", ".join(f'("{i}", {d}, {a})' for i, d, a in effects(decl, path))
        lines.append(f'    ("farmersdelight:{path}", &[{body}]),')
    lines.append("];")
    lines.append("")
    lines.append("/// `hasCustomTooltip` items: `tooltip.farmersdelight.<path>` in blue.")
    lines.append("pub const CUSTOM_TOOLTIPS: &[&str] = &[")
    for path in CUSTOM:
        if path not in decl:
            sys.exit(f"{path}: no declaration")
        lines.append(f'    "farmersdelight:{path}",')
    lines.append("];")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run tools/gen_food_tooltips.py")
            return 1
        print("food tooltips check ok")
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
